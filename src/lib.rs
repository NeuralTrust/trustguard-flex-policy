#[derive(Deserialize)]
struct EvaluateResponse {
    status: String,
    #[serde(default)]
    transformed_payload: Option<Value>,
    #[serde(default)]
    findings: Vec<Value>,
    #[serde(default)]
    trace_id: Option<String>,
    #[serde(default)]
    request_id: Option<String>,
}

enum Verdict {
    Continue,
    Transform(Value),
    Block { reason: String },
}

/// Builds the `/v1/evaluate` request body. Pure and unit-testable on its own
/// (unlike `evaluate`, which needs a live `HttpClient`) -- this is where
/// `content_type`/`session_id`/`attributes.user` are decided.
fn build_evaluate_request_body(
    ctx: &PolicyContext,
    payload: Value,
    direction: &str,
    protocol: &str,
    model_name: Option<&str>,
    attrs: &RequestAttrs,
) -> Value {
    // `content_type` is always sent, regardless of provider/model.
    let mut attributes = json!({ "content_type": "application/json" });
    if model_name.is_some() || attrs.provider_name.is_some() {
        attributes["model"] = json!({
            "name": model_name,
            "provider": attrs.provider_name,
        });
    }

    json!({
        "payload": payload,
        "direction": direction,
        "protocol": protocol,
        "session_id": attrs.session_id,
        "consumer_id": ctx.consumer_id,
        "attributes": attributes,
    })
}

/// Whether `mode: "mirror"` is in effect -- see [`evaluate_and_decide`].
///
/// Don't trust the gateway to have pre-filled `mode`'s schema `default:
/// mirror` -- confirmed in this project that optional
/// properties' defaults are NOT reliably applied before the config reaches
/// the policy, unlike `required: true` properties. Apply the default
/// ourselves: anything other than the literal `"enforce"` (including an
/// absent `mode`) is treated as mirror, so the intended default actually
/// takes effect even when the gateway sends nothing for it.
fn is_mirror_mode(config: &Config) -> bool {
    config.mode.as_deref() != Some("enforce")
}

/// Fires the same `/v1/evaluate` call [`evaluate`] makes, but never awaits its
/// response -- used by [`evaluate_and_decide`] under `mode: "mirror"`, where
/// this policy must add zero latency to the real request/response cycle.
///
/// This is safe because `dispatch_http_call` (pdk-classy's
/// `RequestBuilder::send`, which `.post()` calls) issues the real HTTP call to
/// the TrustGuard cluster eagerly and synchronously, before `.post()` even
/// returns -- `.await`ing the resulting `Request<T>` only arranges to *read* a
/// response that has already been dispatched. Dropping it immediately (via
/// `let _ = ...`) just skips registering a waker/extractor for that response
/// (`Request<T>`'s `Drop` impl removes both): when the response later arrives,
/// the reactor's `notify_response` finds no extractor, stores nothing, and
/// wakes no one -- a silent no-op, not a panic or a stall. We never see
/// TrustGuard's verdict, which is the point: findings for mirrored traffic are
/// only visible in TrustGuard's own Activity log, never via this gateway.
fn dispatch_mirror(
    ctx: &PolicyContext,
    client: &HttpClient,
    payload: Value,
    direction: &str,
    protocol: &str,
    model_name: Option<&str>,
    attrs: &RequestAttrs,
) {
    let config = &ctx.config;
    let request_body = build_evaluate_request_body(ctx, payload, direction, protocol, model_name, attrs);
    let body_bytes = match serde_json::to_vec(&request_body) {
        Ok(b) => b,
        Err(e) => {
            logger::warn!("mirror: failed to serialize trustguard payload: {e}");
            return;
        }
    };
    let auth_header = format!("Bearer {}", config.api_key);
    let timeout_ms = config.timeout_ms.unwrap_or(2000).max(0) as u64;

    logger::info!("mirror: dispatched {direction}/{protocol} evaluate call (fire-and-forget)");
    let _ = client
        .request(&config.trustguard_url)
        .path("/v1/evaluate")
        .headers(vec![
            ("authorization", auth_header.as_str()),
            ("content-type", "application/json"),
        ])
        .body(&body_bytes)
        .timeout(Duration::from_millis(timeout_ms))
        .post();
}

/// Shared entry point for every call site that used to do
/// `decide(evaluate(...).await, ...)` directly: under `mode: "mirror"`, mirrors
/// the payload to TrustGuard via [`dispatch_mirror`] without awaiting it and
/// always reports [`Verdict::Continue`] (mirror mode never blocks/transforms,
/// by design); otherwise behaves exactly as before.
async fn evaluate_and_decide(
    ctx: &PolicyContext,
    client: &HttpClient,
    payload: Value,
    direction: &str,
    protocol: &str,
    model_name: Option<&str>,
    attrs: &RequestAttrs,
    is_input: bool,
) -> Verdict {
    if is_mirror_mode(&ctx.config) {
        dispatch_mirror(ctx, client, payload, direction, protocol, model_name, attrs);
        return Verdict::Continue;
    }
    let eval = evaluate(ctx, client, payload, direction, protocol, model_name, attrs).await;
    decide(eval, &ctx.config, is_input)
}

async fn evaluate(
    ctx: &PolicyContext,
    client: &HttpClient,
    payload: Value,
    direction: &str,
    protocol: &str,
    model_name: Option<&str>,
    attrs: &RequestAttrs,
) -> Result<EvaluateResponse, String> {
    let config = &ctx.config;
    let request_body = build_evaluate_request_body(ctx, payload, direction, protocol, model_name, attrs);

    let body_bytes = serde_json::to_vec(&request_body).map_err(|e| e.to_string())?;
    let auth_header = format!("Bearer {}", config.api_key);
    let timeout_ms = config.timeout_ms.unwrap_or(2000).max(0) as u64;

    let response = client
        .request(&config.trustguard_url)
        .path("/v1/evaluate")
        .headers(vec![
            ("authorization", auth_header.as_str()),
            ("content-type", "application/json"),
        ])
        .body(&body_bytes)
        .timeout(Duration::from_millis(timeout_ms))
        .post()
        .await
        .map_err(|e| format!("trustguard unreachable: {e:?}"))?;

    if response.status_code() >= 400 {
        return Err(format!("trustguard http {}", response.status_code()));
    }

    serde_json::from_slice(response.body()).map_err(|e| format!("bad trustguard body: {e}"))
}

fn decide(eval: Result<EvaluateResponse, String>, config: &Config, is_input: bool) -> Verdict {
    let eval = match eval {
        Ok(e) => e,
        Err(err) => {
            logger::warn!("trustguard evaluate failed: {err}");
            return if config.fail_mode.as_deref() == Some("open") {
                Verdict::Continue
            } else {
                Verdict::Block {
                    reason: "trustguard unavailable (fail-closed)".to_string(),
                }
            };
        }
    };

    if !eval.findings.is_empty() {
        logger::info!(
            "trustguard findings: {} (trace_id={:?}, request_id={:?})",
            eval.findings.len(),
            eval.trace_id,
            eval.request_id
        );
    }

    match eval.status.as_str() {
        "block" => Verdict::Block {
            reason: "blocked by trustguard policy".to_string(),
        },
        "ask" if is_input => {
            if config.ask_behavior.as_deref() == Some("allow") {
                Verdict::Continue
            } else {
                Verdict::Block {
                    reason: "confirmation required (ask) - blocked by gateway config".to_string(),
                }
            }
        }
        "transform" => match eval.transformed_payload {
            Some(payload) => Verdict::Transform(payload),
            None => Verdict::Continue,
        },
        _ => Verdict::Continue,
    }
}

fn block_response<D>(reason: &str) -> Flow<D> {
    Flow::Break(
        Response::new(403)
            .with_headers(vec![("content-type".to_string(), "application/json".to_string())])
            .with_body(json!({ "error": reason }).to_string()),
    )
}

/// Handles a REQUEST body whose shape `build_llm_request_payload` couldn't
/// recognize (not valid JSON, valid JSON without a `messages`/`system`/etc.
/// shape, or a JSON-RPC envelope that isn't an MCP `tools/call` -- e.g. an
/// A2A `message/send` call, or any other protocol this policy doesn't have
/// dedicated parsing for), according to `unrecognizedRequestFormat`:
///  - `allow`: let it through unevaluated (previous, only, behavior).
///  - `block`: reject outright without calling TrustGuard (default).
///  - `analyze`: send the raw payload bytes to TrustGuard as plain text so it
///    still gets evaluated, even though the policy can't parse its structure.
///    A `transform` verdict is treated as `block`: rewriting a body whose
///    structure we don't understand risks sending a broken payload upstream.
async fn handle_unrecognized_request(
    ctx: &PolicyContext,
    client: &HttpClient,
    attrs: &RequestAttrs,
    raw_body: &[u8],
) -> Flow<()> {
    // Don't rely on the gateway pre-filling the schema default for this optional
    // property -- observed in practice to arrive as `None` when not explicitly
    // set in the applied config, unlike `required: true` properties. Apply the
    // schema's declared default ourselves instead.
    //
    // Under `mode: "mirror"` this ignores `unrecognizedRequestFormat` entirely
    // and always takes the analyze path: "block" has no meaning when nothing is
    // ever blocked, so mirroring whatever text is available is strictly more
    // useful than skipping it.
    let mirror = is_mirror_mode(&ctx.config);
    let format = if mirror {
        "analyze"
    } else {
        ctx.config.unrecognized_request_format.as_deref().unwrap_or("analyze")
    };
    match format {
        "allow" => Flow::Continue(()),
        "analyze" => {
            let raw_text = match std::str::from_utf8(raw_body) {
                Ok(s) if !s.trim().is_empty() => s,
                _ => {
                    return if mirror {
                        Flow::Continue(())
                    } else {
                        block_response("unrecognized request format: no analyzable text content")
                    };
                }
            };
            let fallback_payload = build_fallback_payload("user", raw_text, attrs);
            // See `protocol_for`: when this body is a JSON-RPC method the MCP
            // layer doesn't structurally evaluate (e.g. `tools/list`, or A2A's
            // `message/send`), it still reaches this analyze fallback rather
            // than being skipped -- but it should be labeled protocol=mcp, not
            // unconditionally "llm", when we already know it's a JSON-RPC body.
            match evaluate_and_decide(ctx, client, fallback_payload, "input", protocol_for(attrs), None, attrs, true).await {
                Verdict::Continue => Flow::Continue(()),
                Verdict::Block { reason } => block_response(&reason),
                Verdict::Transform(_) => block_response(
                    "transform indicated for unrecognized request format; blocking for safety",
                ),
            }
        }
        _ => block_response("unrecognized request format"),
    }
}

/// Replaces the response body when there is one to write to. `None` is the
/// mirror-mode case: the response has already been streamed to the client and
/// the policy is only looking at its own copy, so there is nothing to rewrite.
fn replace_response_body(body: Option<&ResponseBodyState>, bytes: &[u8]) {
    if let Some(body) = body {
        let _ = body.handler().set_body(bytes);
    }
}

/// Response-side equivalent of [`handle_unrecognized_request`], driven by
/// `unrecognizedResponseFormat`. `transform` is likewise treated as `block` for
/// the same reason: we don't know the response's real structure well enough to
/// safely rewrite it in place.
async fn handle_unrecognized_response(
    ctx: &PolicyContext,
    client: &HttpClient,
    attrs: &RequestAttrs,
    body: Option<&ResponseBodyState>,
    raw_body: &[u8],
) {
    // Same reasoning as handle_unrecognized_request: apply the schema's declared
    // default ourselves rather than trusting the gateway to pre-fill it. Also
    // mirrors its mirror-mode override: see the comment there.
    let mirror = is_mirror_mode(&ctx.config);
    let format = if mirror {
        "analyze"
    } else {
        ctx.config.unrecognized_response_format.as_deref().unwrap_or("analyze")
    };
    match format {
        "allow" => {}
        "analyze" => {
            let raw_text = match std::str::from_utf8(raw_body) {
                Ok(s) if !s.trim().is_empty() => s.to_string(),
                _ => {
                    if !mirror {
                        let error_body = json!({
                            "error": "unrecognized response format: no analyzable text content"
                        })
                        .to_string();
                        replace_response_body(body, error_body.as_bytes());
                    }
                    return;
                }
            };
            let fallback_payload = build_fallback_payload("assistant", &raw_text, attrs);
            // The response itself isn't valid JSON (e.g. a plain-text auth
            // error from an upstream MCP server that never reached its
            // JSON-RPC handler), so `mcp::response_outcome` never runs. Fall
            // back to whatever protocol the request was, rather than always
            // defaulting to "llm" -- otherwise an MCP transaction gets
            // mislabeled on its response leg purely because the upstream
            // errored out before returning JSON-RPC.
            match evaluate_and_decide(ctx, client, fallback_payload, "output", protocol_for(attrs), None, attrs, false).await {
                Verdict::Continue => {}
                Verdict::Transform(_) => {
                    logger::warn!(
                        "trustguard indicated transform for an unrecognized-format response; blocking for safety"
                    );
                    let error_body = json!({
                        "error": "transform indicated for unrecognized response format; blocking for safety"
                    })
                    .to_string();
                    replace_response_body(body, error_body.as_bytes());
                }
                Verdict::Block { reason } => {
                    logger::warn!("trustguard blocked unrecognized-format response: {reason}");
                    let error_body = json!({ "error": reason }).to_string();
                    replace_response_body(body, error_body.as_bytes());
                }
            }
        }
        _ => {
            let error_body = json!({ "error": "unrecognized LLM response format" }).to_string();
            replace_response_body(body, error_body.as_bytes());
        }
    }
}

/// Prefers the explicitly configured `providerName`; falls back to the
/// `x-llm-proxy-llm-provider` header that an upstream proxy policy may set
/// earlier in the chain, when present. That header isn't part of any
/// documented/stable PDK or MuleSoft contract -- it was found by inspecting
/// real request headers on a live gateway, so treat it as best-effort.
fn resolve_provider_name(configured: &Option<String>, headers: &dyn HeadersHandler) -> Option<String> {
    configured
        .clone()
        .filter(|s| !s.trim().is_empty())
        .or_else(|| headers.header("x-llm-proxy-llm-provider"))
}

