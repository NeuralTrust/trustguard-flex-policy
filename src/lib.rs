    #[test]
    fn mcp_non_tools_call_request_falls_through_to_unrecognized_path() {
        // An A2A message/send call is JSON-RPC-shaped but not tools/call: it
        // must be Ignored by the MCP layer (not silently skipped by
        // request_filter) and have no `messages`/`system`/`contents`/`input`
        // shape either, so it lands in the unrecognized-format fallback --
        // which, per `protocol_for`, reports protocol=mcp for it (see below),
        // not the "llm" default this fallback uses for genuinely non-JSON-RPC
        // bodies.
        let body = json!({
            "jsonrpc": "2.0", "id": 1, "method": "message/send",
            "params": {"message": {"role":"user","parts":[{"type":"text","text":"hi"}]}}
        });
        assert!(matches!(crate::mcp::request_outcome(&body), crate::mcp::RequestOutcome::Ignored));
        assert!(build_llm_payload_for_request(&body).is_none());
    }

