const PROTOCOL_LLM: &str = "llm";
const PROTOCOL_MCP: &str = "mcp";

/// The protocol to report to TrustGuard for the unrecognized-format
/// (`analyze`) fallback, on either leg: `mcp` when this transaction's request
/// body was a JSON-RPC envelope (`RequestAttrs::request_was_mcp`), `llm`
/// otherwise. Used whenever the structural MCP/LLM parsers didn't handle the
/// body themselves, so the fallback call is still labeled accurately instead
/// of defaulting to "llm" unconditionally.
fn protocol_for(attrs: &RequestAttrs) -> &'static str {
    if attrs.request_was_mcp {
        PROTOCOL_MCP
    } else {
        PROTOCOL_LLM
    }
}

/// Builds the `analyze`-fallback payload: a single synthetic message wrapping
/// the raw body's text. When `protocol_for` reports `"mcp"`, TrustGuard's own
/// payload validation (`guardpayload.validateMCP`, confirmed live: a bare
/// `{"messages":[...]}` call returns `400 payload: mcp requires a JSON-RPC
/// envelope or messages with tools`) requires a `tools` key too for any
/// non-JSON-RPC `protocol: "mcp"` payload -- an empty array satisfies it.
/// Without this, `protocol_for` correctly labeling the fallback as MCP
/// silently broke every analyze-fallback call for an MCP transaction: the
/// `/v1/evaluate` call failed validation, and with `failMode: open` that
/// failure never surfaced anywhere, not even in TrustGuard's own Activity log.
fn build_fallback_payload(role: &str, text: &str, attrs: &RequestAttrs) -> Value {
    let mut payload = json!({ "messages": [{ "role": role, "content": text }] });
    if attrs.request_was_mcp {
        payload["tools"] = json!([]);
    }
    payload
}

/// Wraps the policy configuration together with runtime metadata resolved once at
/// startup (not part of the user-provided config).
struct PolicyContext {
    config: Config,
    /// Effective consumer_id sent to TrustGuard: the explicit `consumerId` config
    /// value if set, otherwise the name of the API/LLM proxy this policy is
    /// attached to (so TrustGuard can tell requests from different proxies apart
    /// without the operator having to configure `consumerId` by hand).
    consumer_id: Option<String>,
}

/// Per-request attributes, partly resolved from headers at request-header
/// time (the PDK's state machine allows reading headers only before
/// transitioning to the body) and partly completed once the
/// body is available (`finalize_session_id`), then carried through to both
/// the request and the response `evaluate()` calls of the same transaction
/// via `RequestData<RequestAttrs>`.
///
/// There is no `attributes.user` (end-user identity) support: unlike
/// `session_id`, which is harmless to let the caller influence (worst case a
/// spoofed value only confuses `multiturn_guard`'s own turn-grouping), a
/// caller-supplied user id/email would let a client attribute its traffic to
/// someone else for policy/audit purposes with nothing validating it.
/// A trustworthy identity would have to come from the gateway's own
/// authenticated principal, never a raw client header -- this policy has no
/// equivalent signal to read from a generic HTTP proxy position.
#[derive(Clone, Default)]
struct RequestAttrs {
    /// `attributes.model.provider`.
    provider_name: Option<String>,
    /// TrustGuard `session_id`, the `multiturn_guard` anchor.
    session_id: Option<String>,
    /// Whether `session_id` was generated by this policy (no header or body
    /// field produced one) rather than read from the caller. When true,
    /// `response_filter` echoes it back as `X-Session-Id` so the caller can
    /// send it on the next turn.
    session_id_generated: bool,
    /// Whether the REQUEST body was a JSON-RPC envelope (`mcp::is_mcp_envelope`),
    /// regardless of whether it turned out to be an evaluated `tools/call` or
    /// an ignored method. Threaded to the response phase so that
    /// `handle_unrecognized_response`'s fallback picks `protocol: "mcp"`
    /// instead of defaulting to `"llm"` when the response itself isn't valid
    /// JSON (e.g. a plain-text auth error from the upstream MCP server) and
    /// `mcp::response_outcome` never gets a chance to recognize it as MCP.
    request_was_mcp: bool,
    /// The MCP method of the REQUEST (`mcp::mcp_method`), when it was an MCP
    /// protocol message. Lets the response phase skip MCP messages other than
    /// `tools/call` the same way the request phase does.
    mcp_method: Option<String>,
    /// Whether the REQUEST asked for a streamed response (`"stream": true`, or
    /// a streaming path for Gemini/Bedrock). Threaded to the response phase,
    /// which never evaluates these before forwarding them -- that would mean
    /// buffering the *entire* upstream stream (`pdk-classy`'s
    /// `BodyExchange::new` waits for `end_of_stream`), turning token-by-token
    /// delivery into one burst at the end. In either mode the stream is
    /// forwarded as it arrives and its reassembled text is only audited
    /// afterwards (see `audit_streamed_llm_output`).
    is_streaming: bool,
    /// Whether the REQUEST is framed as an upgrade whose body is skipped (see
    /// `classify_upgrade`): a genuine WebSocket handshake, or, in mirror mode
    /// only, an unverifiable upgrade passed through unevaluated. Threaded to the response phase so BOTH legs skip
    /// body handling entirely for it -- unlike streaming, this isn't about
    /// losing coverage, it's about not hanging the connection. Confirmed
    /// live: once a connection upgrades, every frame after the handshake is
    /// still carried as this exchange's "body" at the proxy-wasm level, but
    /// that body's `end_of_stream` never arrives until the whole connection
    /// closes -- `into_body_state()` (in either `mode`) pauses waiting for
    /// it regardless, freezing the first frame sent after the handshake
    /// forever. See `is_websocket_upgrade`.
    is_websocket_upgrade: bool,
}

/// Well-known session header names recognized out of the box, tried in order
/// after the configured `sessionIdHeader` (if any). Hardcoded, not
/// configurable -- unlike a caller-supplied identity header, a session
/// correlation id is low-stakes either way (see `RequestAttrs` docs), so
/// baking in common names gives free interop with chat front-ends that send
/// them, without asking the operator to type an exact header name to get that
/// coverage.
const KNOWN_SESSION_HEADERS: [&str; 2] = ["X-Session-Id", "X-OpenWebUI-Chat-Id"];

/// The header `response_filter` sets when `RequestAttrs.session_id_generated`
/// is true, so the caller can echo it back on its next turn.
const SESSION_ID_RESPONSE_HEADER: &str = "X-Session-Id";

/// Reads `header_name` (a config value naming a header, e.g. `sessionIdHeader`)
/// from `headers`, returning `None` when unconfigured, absent, or blank.
fn resolve_from_header(headers: &dyn HeadersHandler, header_name: &Option<String>) -> Option<String> {
    let name = header_name.as_deref()?.trim();
    if name.is_empty() {
        return None;
    }
    headers.header(name).filter(|v| !v.trim().is_empty())
}

/// First step of session_id resolution, run at header time: the configured
/// `sessionIdHeader` override, then the well-known session headers.
fn resolve_session_id_from_headers(config: &Config, headers: &dyn HeadersHandler) -> Option<String> {
    if let Some(id) = resolve_from_header(headers, &config.session_id_header) {
        return Some(id);
    }
    KNOWN_SESSION_HEADERS
        .iter()
        .find_map(|name| headers.header(name).filter(|v| !v.trim().is_empty()))
}

/// Second step, run once the body is parsed: a named field in the JSON body,
/// named by `sessionIdBodyField`.
fn resolve_session_id_from_body(config: &Config, body: &Value) -> Option<String> {
    let field = config.session_id_body_field.as_deref()?.trim();
    if field.is_empty() {
        return None;
    }
    body.get(field).and_then(|v| v.as_str()).filter(|s| !s.trim().is_empty()).map(str::to_string)
}

/// Completes `attrs.session_id`: tries the body field (when `body` parsed and
/// `sessionIdBodyField` is configured), then generates a fresh id as a last
/// resort (header(s) -> body field -> generate), so `multiturn_guard` never silently loses
/// coverage just because a caller sent no session hint at all. `body` is
/// `None` when the request body isn't valid JSON (nothing to look a field up
/// in); generation still applies in that case.
fn finalize_session_id(config: &Config, attrs: &mut RequestAttrs, body: Option<&Value>) {
    if attrs.session_id.is_some() {
        return;
    }
    if let Some(body) = body {
        if let Some(id) = resolve_session_id_from_body(config, body) {
            attrs.session_id = Some(id);
            return;
        }
    }
    attrs.session_id = Some(uuid::Uuid::new_v4().to_string());
    attrs.session_id_generated = true;
}

fn resolve_request_attrs(config: &Config, headers: &dyn HeadersHandler) -> RequestAttrs {
    RequestAttrs {
        provider_name: resolve_provider_name(&config.provider_name, headers),
        session_id: resolve_session_id_from_headers(config, headers),
        session_id_generated: false,
        // Not knowable until headers/body are inspected; request_filter fills these in.
        request_was_mcp: false,
        mcp_method: None,
        is_streaming: false,
        is_websocket_upgrade: false,
    }
}

