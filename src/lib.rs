// Building the REQUEST payload (protocol=llm, messages[] + tools[])
// ---------------------------------------------------------------------------

fn build_llm_request_payload(body: &Value) -> Option<Value> {
    let mut messages: Vec<Value> = Vec::new();

    if let Some(system) = body.get("system").and_then(|v| v.as_str()) {
        if !system.trim().is_empty() {
            messages.push(json!({ "role": "system", "content": system }));
        }
    }

    let has_native_messages = body.get("messages").and_then(|v| v.as_array()).is_some();
    if let Some(existing) = body.get("messages").and_then(|v| v.as_array()) {
        messages.extend(existing.iter().cloned());
    }

    if !has_native_messages && messages.is_empty() {
        return None;
    }

    let has_content = messages.iter().any(|m| {
        m.get("content")
            .and_then(|c| c.as_str())
            .map(|s| !s.trim().is_empty())
            .unwrap_or(false)
    });
    if !has_content {
        return None;
    }

    let mut payload = json!({ "messages": messages });
    if let Some(tools) = body.get("tools") {
        // Normalizes Anthropic's native {name,description,input_schema} tools to
        // the {type:"function",function:{...}} shape TrustGuard expects;
        // already OpenAI-shaped tools (OpenAI, Mistral, OpenRouter, Cohere)
        // pass through unchanged.
        if let Some(normalized) = normalize_chat_tools(tools) {
            payload["tools"] = normalized;
        }
    }
    Some(payload)
}

