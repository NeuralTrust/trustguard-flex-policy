fn extract_response_text(body: &Value) -> Option<String> {
    if let Some(text) = body.pointer("/choices/0/message/content").and_then(|v| v.as_str()) {
        return Some(text.to_string());
    }
    if let Some(text) = body.pointer("/choices/0/text").and_then(|v| v.as_str()) {
        return Some(text.to_string());
    }
    if let Some(blocks) = body.get("content").and_then(|v| v.as_array()) {
        let combined: String = blocks
            .iter()
            .filter_map(|b| b.get("text").and_then(|t| t.as_str()))
            .collect::<Vec<_>>()
            .join("");
        if !combined.is_empty() {
            return Some(combined);
        }
    }
    None
}

fn extract_response_tool_calls(body: &Value) -> Option<Value> {
    body.pointer("/choices/0/message/tool_calls").cloned()
}

fn rebuild_response_body(original: &Value, new_text: &str) -> Value {
    let mut updated = original.clone();
    if updated.pointer("/choices/0/message/content").is_some() {
        updated["choices"][0]["message"]["content"] = json!(new_text);
    } else if updated.pointer("/choices/0/text").is_some() {
        updated["choices"][0]["text"] = json!(new_text);
    } else if updated.get("content").and_then(|v| v.as_array()).is_some() {
        updated["content"] = json!([{ "type": "text", "text": new_text }]);
    }
    updated
}

