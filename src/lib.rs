fn joined_transformed_messages(payload: &Value) -> Option<String> {
    let arr = payload.get("messages")?.as_array()?;
    let parts: Vec<&str> = arr
        .iter()
        .filter_map(|m| m.get("content").and_then(|c| c.as_str()))
        .filter(|s| !s.trim().is_empty())
        .collect();
    if parts.is_empty() {
        None
    } else {
        Some(parts.join("\n"))
    }
}

fn transformed_input(payload: &Value) -> Option<String> {
    if let Some(s) = payload.get("input").and_then(|v| v.as_str()) {
        return Some(s.to_string());
    }
    joined_transformed_messages(payload)
}

enum SegmentPath {
    SystemField,
    MessageIndex(usize),
}

struct Segment {
    path: SegmentPath,
    original_content: String,
}

fn collect_request_segments(body: &Value) -> Vec<Segment> {
    let mut segs = Vec::new();
    if let Some(system) = body.get("system").and_then(|v| v.as_str()) {
        if !system.trim().is_empty() {
            segs.push(Segment {
                path: SegmentPath::SystemField,
                original_content: system.to_string(),
            });
        }
    }
    if let Some(arr) = body.get("messages").and_then(|v| v.as_array()) {
        for (i, m) in arr.iter().enumerate() {
            if let Some(c) = m.get("content").and_then(|v| v.as_str()) {
                if !c.trim().is_empty() {
                    segs.push(Segment {
                        path: SegmentPath::MessageIndex(i),
                        original_content: c.to_string(),
                    });
                }
            }
        }
    }
    segs
}

fn redistribute(masked: &str, segments: &[Segment]) -> Option<Vec<String>> {
    let masked_lines: Vec<&str> = masked.split('\n').collect();
    let counts: Vec<usize> = segments
        .iter()
        .map(|s| s.original_content.matches('\n').count() + 1)
        .collect();
    let total: usize = counts.iter().sum();
    if total != masked_lines.len() {
        return None;
    }
    let mut out = Vec::with_capacity(segments.len());
    let mut idx = 0;
    for count in counts {
        out.push(masked_lines[idx..idx + count].join("\n"));
        idx += count;
    }
    Some(out)
}

fn apply_masked_request(original: &Value, masked: &str) -> Option<Value> {
    let segments = collect_request_segments(original);
    if segments.is_empty() {
        return None;
    }
    let pieces = redistribute(masked, &segments)?;
    let mut updated = original.clone();
    for (seg, piece) in segments.iter().zip(pieces.iter()) {
        match seg.path {
            SegmentPath::SystemField => updated["system"] = json!(piece),
            SegmentPath::MessageIndex(i) => updated["messages"][i]["content"] = json!(piece),
        }
    }
    Some(updated)
}

