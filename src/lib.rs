/// Whether the request path alone signals a streaming call, for providers
/// that don't use a `"stream": true` body field -- unlike OpenAI/Anthropic/
/// Responses/Cohere, where the request body is otherwise byte-for-byte
/// identical between streaming and non-streaming calls:
///  - Gemini/Vertex distinguishes via the `:streamGenerateContent` method
///    suffix in the path (vs. `:generateContent`).
///  - AWS Bedrock's Converse API distinguishes via the `/converse-stream`
///    path segment (vs. `/converse`) -- same request body either way.
fn path_signals_streaming(path: &str) -> bool {
    path.contains(":streamGenerateContent") || path.contains("/converse-stream")
}

/// How a request relates to HTTP/1.1 upgrade framing (ENG-3374).
#[derive(Debug, PartialEq, Eq)]
enum UpgradeKind {
    /// No upgrade requested, or an `h2c` upgrade, whose headers Envoy strips
    /// before serving it as a plain request with a normal body.
    None,
    /// A genuine RFC 6455 WebSocket handshake: `GET`, `Connection: Upgrade`,
    /// `Upgrade: websocket`, a `Sec-WebSocket-Key` and no body.
    WebSocket,
    /// Envoy frames it as an upgrade (`Connection: Upgrade` plus any other
    /// `Upgrade` value), so its body never reaches `end_of_stream` and can't
    /// be evaluated -- yet it isn't a genuine WebSocket handshake. Confirmed
    /// live: a POST carrying forged handshake headers reaches the upstream
    /// with its body unevaluated, so these are rejected in enforce mode.
    Unverifiable,
}

fn classify_upgrade(headers: &dyn HeadersHandler) -> UpgradeKind {
    let connection_has_upgrade = headers
        .header("connection")
        .map(|v| v.to_ascii_lowercase().contains("upgrade"))
        .unwrap_or(false);
    let upgrade = headers.header("upgrade").map(|v| v.trim().to_ascii_lowercase());
    let upgrade = match upgrade {
        Some(u) if connection_has_upgrade && !u.is_empty() => u,
        _ => return UpgradeKind::None,
    };
    if upgrade == "h2c" {
        return UpgradeKind::None;
    }

    let is_get = headers.header(":method").is_some_and(|m| m.eq_ignore_ascii_case("GET"));
    let has_body = headers.header("transfer-encoding").is_some()
        || headers
            .header("content-length")
            .is_some_and(|v| v.trim().parse::<u64>().map_or(true, |n| n > 0));
    let genuine = is_get
        && !has_body
        && upgrade == "websocket"
        && headers.header("sec-websocket-key").is_some();
    if genuine {
        UpgradeKind::WebSocket
    } else {
        UpgradeKind::Unverifiable
    }
}

async fn request_filter(
    state: RequestState,
    ctx: Rc<PolicyContext>,
    client: HttpClient,
) -> Flow<RequestAttrs> {
    let headers_state = state.into_headers_state().await;
    let path = headers_state.path();
    let mut attrs = resolve_request_attrs(&ctx.config, headers_state.handler());

    // Checked before anything else touches the body: see
    // `RequestAttrs::is_websocket_upgrade`'s doc comment for why this isn't
    // optional the way skipping streaming evaluation is -- getting this
    // wrong hangs the connection, not just loses coverage.
    match classify_upgrade(headers_state.handler()) {
        UpgradeKind::None => {}
        UpgradeKind::WebSocket => {
            attrs.is_websocket_upgrade = true;
            return Flow::Continue(attrs);
        }
        UpgradeKind::Unverifiable => {
            if !is_mirror_mode(&ctx.config) {
                logger::warn!("rejecting upgrade request that is not a valid WebSocket handshake");
                return block_response("upgrade request is not a valid WebSocket handshake");
            }
            // Mirror mode never blocks; skip the body so it can't hang.
            logger::warn!("mirror: upgrade request is not a valid WebSocket handshake, passing it through unevaluated");
            attrs.is_websocket_upgrade = true;
            return Flow::Continue(attrs);
        }
    }

    attrs.is_streaming = path_signals_streaming(&path);

    if !headers_state.contains_body() {
        return Flow::Continue(attrs);
    }

    // Same reasoning as in `response_filter`: a `transform` verdict can rewrite
    // the body to a different size, and the original `Content-Length` would
    // make the upstream wait for bytes that never arrive. Not needed in mirror
    // mode, which never modifies the request.
    if !is_mirror_mode(&ctx.config) {
        headers_state.handler().remove_header("content-length");
    }

    let body_state = headers_state.into_body_state().await;
    let raw_body = body_state.handler().body();

    let parsed: Option<Value> = serde_json::from_slice(&raw_body).ok();
    finalize_session_id(&ctx.config, &mut attrs, parsed.as_ref());

    let original_body: Value = match parsed {
        Some(v) => v,
        None => {
            return match handle_unrecognized_request(&ctx, &client, &attrs, &raw_body).await {
                Flow::Continue(()) => Flow::Continue(attrs),
                Flow::Break(response) => Flow::Break(response),
            };
        }
    };

    attrs.request_was_mcp = mcp::is_mcp_envelope(&original_body);
    attrs.mcp_method = mcp::mcp_method(&original_body);
    // OR'd with the path-based check already done above: OpenAI/Anthropic/
    // Responses/Cohere signal streaming via this body field instead of a
    // distinct path.
    attrs.is_streaming =
        attrs.is_streaming || original_body.get("stream").and_then(|v| v.as_bool()).unwrap_or(false);

    match mcp::request_outcome(&original_body) {
        mcp::RequestOutcome::Evaluate { payload, units } => {
            return match evaluate_and_decide(&ctx, &client, payload, "input", PROTOCOL_MCP, None, &attrs, true).await {
                Verdict::Continue => Flow::Continue(attrs),
                Verdict::Transform(transformed) => {
                    let masked_text = transformed_input(&transformed);
                    let new_body =
                        mcp::apply_request_transform(&original_body, &transformed, &units, masked_text.as_deref());
                    match new_body {
                        Some(new_body) => match serde_json::to_vec(&new_body) {
                            Ok(bytes) => match body_state.handler().set_body(&bytes) {
                                Ok(()) => Flow::Continue(attrs),
                                Err(_) => block_response("failed to apply transformed request body"),
                            },
                            Err(_) => block_response("failed to serialize transformed request body"),
                        },
                        None => block_response("transform could not be safely applied"),
                    }
                }
                Verdict::Block { reason } => block_response(&reason),
            };
        }
        // An MCP protocol message other than `tools/call` (`initialize`,
        // `ping`, notifications, list/read requests, ...) carries nothing
        // worth scanning, so it isn't evaluated. Any other JSON-RPC body (e.g.
        // A2A's `message/send`) deliberately falls through to the generic
        // analyze/block/allow fallback below, so it keeps being scanned.
        mcp::RequestOutcome::Ignored if attrs.mcp_method.is_some() => return Flow::Continue(attrs),
        mcp::RequestOutcome::NotMcp | mcp::RequestOutcome::Ignored => {}
    }

    let built = build_llm_payload_for_request(&original_body);
    let (llm_payload, units) = match built {
        Some(v) => v,
        None => {
            return match handle_unrecognized_request(&ctx, &client, &attrs, &raw_body).await {
                Flow::Continue(()) => Flow::Continue(attrs),
                Flow::Break(response) => Flow::Break(response),
            };
        }
    };

    let model_name = original_body.get("model").and_then(|v| v.as_str());

    match evaluate_and_decide(&ctx, &client, llm_payload, "input", PROTOCOL_LLM, model_name, &attrs, true).await {
        Verdict::Continue => Flow::Continue(attrs),
        Verdict::Transform(transformed) => {
            let masked = match transformed_input(&transformed) {
                Some(m) => m,
                None => return block_response("transform indicated but no payload to apply"),
            };
            let new_body = match &units {
                None => apply_masked_request(&original_body, &masked),
                Some(units) => redistribute_units(&masked, units)
                    .and_then(|pieces| apply_units(&original_body, units, &pieces)),
            };
            match new_body {
                Some(new_body) => match serde_json::to_vec(&new_body) {
                    Ok(bytes) => match body_state.handler().set_body(&bytes) {
                        Ok(()) => Flow::Continue(attrs),
                        Err(_) => block_response("failed to apply transformed request body"),
                    },
                    Err(_) => block_response("failed to serialize transformed request body"),
                },
                None => block_response("transform could not be safely applied"),
            }
        }
        Verdict::Block { reason } => block_response(&reason),
    }
}

/// Dispatches request-body extraction to the matching provider format: the existing
/// full-fidelity OpenAI/Anthropic path (`build_llm_request_payload`), or one
/// of the `formats` module's structural parsers for Gemini/Vertex, Bedrock,
/// and the OpenAI Responses API. Returns the `payload` to send to TrustGuard
/// plus, for the non-Chat shapes, the `TextUnit`s needed to splice a
/// `transform` verdict back into the native body (`None` for Chat, which
/// keeps using its own `collect_request_segments`/`apply_masked_request`).
fn build_llm_payload_for_request(body: &Value) -> Option<(Value, Option<Vec<TextUnit>>)> {
    match detect_request_format(body) {
        ReqFormat::Chat => build_llm_request_payload(body).map(|p| (p, None)),
        ReqFormat::Gemini => {
            let units = gemini_request_units(body);
            if units.is_empty() {
                return None;
            }
            let mut payload = json!({ "messages": units_to_messages(&units) });
            if let Some(tools) = gemini_request_tools(body) {
                payload["tools"] = tools;
            }
            Some((payload, Some(units)))
        }
        ReqFormat::Bedrock => {
            let units = bedrock_request_units(body);
            if units.is_empty() {
                return None;
            }
            let mut payload = json!({ "messages": units_to_messages(&units) });
            if let Some(tools) = bedrock_request_tools(body) {
                payload["tools"] = tools;
            }
            Some((payload, Some(units)))
        }
        ReqFormat::Responses => {
            let units = responses_request_units(body);
            if units.is_empty() {
                return None;
            }
            let mut payload = json!({ "messages": units_to_messages(&units) });
            if let Some(tools) = responses_request_tools(body) {
                payload["tools"] = tools;
            }
            Some((payload, Some(units)))
        }
    }
}

/// What to do with an evaluated MCP response, independent of how it's framed
/// on the wire (plain JSON or SSE).
enum McpResponseAction {
    Keep,
    Rewrite(Value),
    Reject(String),
}

/// JSON-RPC error code sent back when an MCP response delivered over SSE is
/// blocked (the -32000..-32099 range is reserved for server-defined errors).
const MCP_BLOCKED_ERROR_CODE: i64 = -32001;

/// Evaluates an MCP response `message` (whose `payload`/`units` come from
/// `mcp::response_outcome`) and decides the action. A transform that can't be
/// applied safely is rejected rather than forwarded unmasked.
async fn decide_mcp_response(
    ctx: &PolicyContext,
    client: &HttpClient,
    attrs: &RequestAttrs,
    message: &Value,
    payload: Value,
    units: &[TextUnit],
) -> McpResponseAction {
    match evaluate_and_decide(ctx, client, payload, "output", PROTOCOL_MCP, None, attrs, false).await {
        Verdict::Continue => McpResponseAction::Keep,
        Verdict::Transform(transformed) => {
            let masked_text = transformed_input(&transformed);
            match mcp::apply_response_transform(message, &transformed, units, masked_text.as_deref()) {
                Some(rewritten) => McpResponseAction::Rewrite(rewritten),
                None => {
                    logger::warn!("trustguard transform could not be safely applied to mcp response; blocking for safety");
                    McpResponseAction::Reject("transform could not be safely applied".to_string())
                }
            }
        }
        Verdict::Block { reason } => {
            logger::warn!("trustguard blocked mcp response: {reason}");
            McpResponseAction::Reject(reason)
        }
    }
}

/// Handles an MCP response delivered as Server-Sent Events. Returns `false`
/// (leaving the body untouched) when the stream holds no evaluable JSON-RPC
/// response, so the caller can fall back to the unrecognized-format path.
///
/// A rewrite replaces only the response event's data, keeping the rest of the
/// stream. A block replaces the whole stream with a single JSON-RPC error
/// event for the same request id, so the MCP client still gets a well-formed
/// SSE reply it can parse (a plain `{"error": ...}` body would not be).
async fn handle_mcp_sse_response(
    ctx: &PolicyContext,
    client: &HttpClient,
    attrs: &RequestAttrs,
    body: Option<&ResponseBodyState>,
    raw_body: &[u8],
) -> bool {
    let Ok(text) = std::str::from_utf8(raw_body) else {
        return false;
    };
    let Some((index, message)) = mcp::sse_find_jsonrpc_response(text) else {
        return false;
    };
    let (payload, units) = match mcp::response_outcome(&message) {
        mcp::ResponseOutcome::Evaluate { payload, units } => (payload, units),
        mcp::ResponseOutcome::NotMcp | mcp::ResponseOutcome::Ignored => return false,
    };

    match decide_mcp_response(ctx, client, attrs, &message, payload, &units).await {
        McpResponseAction::Keep => {}
        McpResponseAction::Rewrite(rewritten) => {
            let new_body = mcp::sse_replace_event_data(text, index, &rewritten.to_string());
            replace_response_body(body, new_body.as_bytes());
        }
        McpResponseAction::Reject(reason) => {
            let error = json!({
                "jsonrpc": "2.0",
                "id": message.get("id").cloned().unwrap_or(Value::Null),
                "error": { "code": MCP_BLOCKED_ERROR_CODE, "message": reason },
            });
            replace_response_body(body, mcp::sse_single_message_body(&error).as_bytes());
        }
    }
    true
}

async fn response_filter(
    state: ResponseState,
    request_data: RequestData<RequestAttrs>,
    ctx: Rc<PolicyContext>,
    client: HttpClient,
) {
    // If the request was already rejected (by this policy or an earlier one
    // in the chain), or cancelled, there is no real provider response to evaluate.
    let mut attrs = match request_data {
        RequestData::Continue(attrs) => attrs,
        _ => return,
    };

    // See `RequestAttrs::is_websocket_upgrade`: skip this leg entirely,
    // before touching headers or body at all, for the same reason -- merely
    // transitioning into body state on the 101 response would hang on the
    // first frame.
    if attrs.is_websocket_upgrade {
        return;
    }

    if !ctx.config.evaluate_response.unwrap_or(true) {
        return;
    }

    let headers_state = state.into_headers_state().await;
    // Prefer the provider resolved on the request phase: response-phase policies
    // that add `x-llm-proxy-llm-provider` run *after*
    // us on the way back (policy chains run in reverse order on the response
    // path), so that header isn't set yet when we get here. session_id doesn't
    // have a response-phase fallback -- it's request-scoped and read/finalized
    // once, same as before.
    if attrs.provider_name.is_none() {
        attrs.provider_name = resolve_provider_name(&ctx.config.provider_name, headers_state.handler());
    }

    // Echo a policy-generated session id back to the caller so it can send it
    // on the next turn, via the same response header. A caller-supplied
    // session id (from a header or the body) is never echoed back: it's
    // already the caller's own value, nothing to hand back.
    if attrs.session_id_generated {
        if let Some(id) = &attrs.session_id {
            headers_state.handler().set_header(SESSION_ID_RESPONSE_HEADER, id);
        }
    }

    let mirror = is_mirror_mode(&ctx.config);

    // MCP protocol messages other than `tools/call` aren't evaluated (see
    // `request_filter`), with one exception: a `tools/list` result, whose tool
    // descriptions are scored for indirect prompt injection. Returning here,
    // before the body is read, also leaves those responses fully untouched.
    let mcp_non_tools_call = matches!(attrs.mcp_method.as_deref(), Some(m) if m != "tools/call");
    if mcp_non_tools_call && attrs.mcp_method.as_deref() != Some("tools/list") {
        return;
    }

    if !headers_state.contains_body() {
        return;
    }

    // Read before the transition to the body state, which consumes the headers.
    let is_sse = headers_state
        .handler()
        .header("content-type")
        .map(|v| v.to_ascii_lowercase().contains("text/event-stream"))
        .unwrap_or(false);

    // A streamed LLM response is never held back, in either mode: evaluating
    // it before forwarding would mean buffering the whole stream
    // (`into_body_state()` waits for `end_of_stream`), turning token-by-token
    // delivery into one burst at the end. Instead it's forwarded as it arrives
    // and its reassembled text is sent to TrustGuard once it has ended -- for
    // audit only, since the client already has it: the verdict isn't applied,
    // even in enforce mode.
    if attrs.is_streaming {
        audit_streamed_llm_output(&ctx, &client, &attrs, headers_state).await;
        return;
    }

    if mirror {
        mirror_response(&ctx, &client, &attrs, headers_state, is_sse, mcp_non_tools_call).await;
        return;
    }

    // The response headers are released before this policy can read the body,
    // so if a `block`/`transform` verdict replaces the body with one of a
    // different size, the upstream's original `Content-Length` would no longer
    // match it and the client would get a truncated response. Drop it now so
    // the gateway frames the (possibly rewritten) body itself.
    headers_state.handler().remove_header("content-length");

    let body_state = headers_state.into_body_state().await;
    let raw_body = body_state.handler().body();
    evaluate_response_body(&ctx, &client, &attrs, &raw_body, is_sse, mcp_non_tools_call, Some(&body_state)).await;
}

/// Upper bound on how much of a response mirror mode keeps as its copy for
/// TrustGuard. The response itself is never held back; past this size the
/// copy is dropped (and logged) instead of growing without limit, e.g. on a
/// long-lived stream.
const MIRROR_COPY_MAX_BYTES: usize = 4 * 1024 * 1024;

/// Reads the response body chunk by chunk through the PDK's body *stream*
/// state, which -- unlike `into_body_state()` -- doesn't pause the response:
/// every chunk reaches the client as soon as it arrives, streaming included.
/// Returns the policy's own copy once the response has ended, or `None` if it
/// was empty or exceeded `MIRROR_COPY_MAX_BYTES`.
async fn copy_response_without_holding(headers_state: ResponseHeadersState) -> Option<Vec<u8>> {
    let stream_state = headers_state.into_body_stream_state().await;
    let mut stream = stream_state.stream();
    let mut copy: Vec<u8> = Vec::new();
    let mut copying = true;
    while let Some(chunk) = stream.next().await {
        if !copying {
            continue;
        }
        let bytes = chunk.bytes();
        if copy.len() + bytes.len() > MIRROR_COPY_MAX_BYTES {
            logger::warn!("response is larger than {MIRROR_COPY_MAX_BYTES} bytes; not copied to TrustGuard");
            copying = false;
            copy = Vec::new();
        } else {
            copy.extend_from_slice(bytes);
        }
    }
    if copying && !copy.is_empty() {
        Some(copy)
    } else {
        None
    }
}

/// Mirror mode's response leg: the response is forwarded as it arrives (see
/// `copy_response_without_holding`) and, once it has ended, the policy's copy
/// is sent to TrustGuard exactly as enforce mode would evaluate it (the
/// verdict is never applied in mirror mode).
///
/// Only responses worth evaluating are copied. An SSE response is copied when
/// it answers an MCP `tools/call`/`tools/list` (streamed LLM responses are
/// handled by `audit_streamed_llm_output`); any other SSE response -- e.g. an
/// MCP server's long-lived `GET` notification stream -- is passed through
/// without being read at all.
async fn mirror_response(
    ctx: &PolicyContext,
    client: &HttpClient,
    attrs: &RequestAttrs,
    headers_state: ResponseHeadersState,
    is_sse: bool,
    mcp_non_tools_call: bool,
) {
    if is_sse && attrs.mcp_method.is_none() {
        return;
    }
    if let Some(copy) = copy_response_without_holding(headers_state).await {
        evaluate_response_body(ctx, client, attrs, &copy, is_sse, mcp_non_tools_call, None).await;
    }
}

/// Streamed LLM responses, in either mode: forwarded as they arrive, then
/// the assistant text reassembled from the stream is sent to TrustGuard,
/// fire-and-forget, for audit. The verdict isn't applied (the client already
/// has the response), and not waiting for it keeps the end of the stream
/// from being delayed. Streams whose format isn't recognized, or that carry
/// no text, aren't sent.
async fn audit_streamed_llm_output(
    ctx: &PolicyContext,
    client: &HttpClient,
    attrs: &RequestAttrs,
    headers_state: ResponseHeadersState,
) {
    let Some(copy) = copy_response_without_holding(headers_state).await else {
        return;
    };
    let Some((text, model_name)) = std::str::from_utf8(&copy).ok().and_then(formats::streamed_response_text) else {
        return;
    };
    let payload = json!({ "messages": [{ "role": "assistant", "content": text }] });
    if !is_mirror_mode(&ctx.config) {
        logger::info!("streamed output sent to TrustGuard for audit only; its verdict is not applied");
    }
    dispatch_mirror(ctx, client, payload, "output", PROTOCOL_LLM, model_name.as_deref(), attrs);
}

/// Evaluates a complete response body. With `body`, the verdict is applied
/// to the response (enforce mode); with `None`, the policy is looking at its
/// own copy of an already-forwarded response (mirror mode), so nothing is
/// written.
async fn evaluate_response_body(
    ctx: &PolicyContext,
    client: &HttpClient,
    attrs: &RequestAttrs,
    raw_body: &[u8],
    is_sse: bool,
    mcp_non_tools_call: bool,
    body: Option<&ResponseBodyState>,
) {

    // An MCP server on the Streamable HTTP transport may answer with SSE
    // instead of plain JSON. Evaluate the JSON-RPC response inside it the same
    // structured way; if there's nothing evaluable in it, fall through to the
    // existing unrecognized-format handling below, as before.
    if is_sse && attrs.request_was_mcp && handle_mcp_sse_response(ctx, client, attrs, body, raw_body).await {
        return;
    }

    // A `tools/list` result is only evaluated structurally; anything else in
    // its response never goes through the generic fallback.
    let original_body: Value = match serde_json::from_slice(raw_body) {
        Ok(v) => v,
        Err(_) => {
            if !mcp_non_tools_call {
                handle_unrecognized_response(ctx, client, attrs, body, raw_body).await;
            }
            return;
        }
    };

    match mcp::response_outcome(&original_body) {
        mcp::ResponseOutcome::Evaluate { payload, units } => {
            match decide_mcp_response(ctx, client, attrs, &original_body, payload, &units).await {
                McpResponseAction::Keep => {}
                McpResponseAction::Rewrite(rewritten) => {
                    if let Ok(bytes) = serde_json::to_vec(&rewritten) {
                        replace_response_body(body, &bytes);
                    }
                }
                McpResponseAction::Reject(reason) => {
                    let error_body = json!({ "error": reason }).to_string();
                    replace_response_body(body, error_body.as_bytes());
                }
            }
            return;
        }
        mcp::ResponseOutcome::NotMcp | mcp::ResponseOutcome::Ignored if mcp_non_tools_call => return,
        // See the matching comment in `request_filter`: fall through to the
        // existing fallback rather than silently skipping A2A/other JSON-RPC
        // response shapes.
        mcp::ResponseOutcome::NotMcp | mcp::ResponseOutcome::Ignored => {}
    }

    let (extracted_text, tool_calls, units) = match extract_response_for(&original_body) {
        Some(v) => v,
        None => {
            logger::warn!("unrecognized LLM response shape, cannot normalize for TrustGuard");
            handle_unrecognized_response(ctx, client, attrs, body, raw_body).await;
            return;
        }
    };

    if extracted_text.trim().is_empty() && tool_calls.is_none() {
        return;
    }

    let mut msg = json!({ "role": "assistant", "content": extracted_text.clone() });
    if let Some(tc) = &tool_calls {
        msg["tool_calls"] = tc.clone();
    }
    let llm_payload = json!({ "messages": [msg] });

    let model_name = original_body.get("model").and_then(|v| v.as_str());

    match evaluate_and_decide(ctx, client, llm_payload, "output", PROTOCOL_LLM, model_name, attrs, false).await {
        Verdict::Continue => {}
        Verdict::Transform(transformed) => {
            let masked = transformed_input(&transformed).unwrap_or_else(|| extracted_text.clone());
            let rebuilt = match &units {
                None => Some(rebuild_response_body(&original_body, &masked)),
                Some(units) => redistribute_units(&masked, units)
                    .and_then(|pieces| apply_units(&original_body, units, &pieces)),
            };
            match rebuilt {
                Some(rebuilt) => {
                    if let Ok(bytes) = serde_json::to_vec(&rebuilt) {
                        replace_response_body(body, &bytes);
                    }
                }
                None => {
                    logger::warn!(
                        "trustguard transform could not be safely applied to response; blocking for safety"
                    );
                    let error_body =
                        json!({ "error": "transform could not be safely applied" }).to_string();
                    replace_response_body(body, error_body.as_bytes());
                }
            }
        }
        Verdict::Block { reason } => {
            logger::warn!("trustguard blocked response: {reason}");
            // The provider's response already reached the gateway; we replace it with
            // an error so it isn't leaked to the client.
            let error_body = json!({ "error": reason }).to_string();
            replace_response_body(body, error_body.as_bytes());
        }
    }
}

/// Response-side counterpart of [`build_llm_payload_for_request`]. Returns
/// the extracted assistant text, any tool calls, and (for the non-Chat
/// shapes) the `TextUnit`s needed to splice a `transform` verdict back into
/// the native response body.
fn extract_response_for(body: &Value) -> Option<(String, Option<Value>, Option<Vec<TextUnit>>)> {
    match detect_response_format(body) {
        RespFormat::Chat => {
            if body.pointer("/choices/0/message/content").is_some() || body.pointer("/choices/0/text").is_some() {
                // OpenAI Chat Completions shape: keep the existing single-block
                // extraction/rewrite path (`extract_response_text`/
                // `rebuild_response_body`) untouched.
                let text = extract_response_text(body)?;
                Some((text, extract_response_tool_calls(body), None))
            } else {
                // Anthropic Messages shape (top-level `content[]` blocks). Uses
                // TextUnit so a `transform` rewrite touches only the `text`
                // blocks and leaves any `tool_use` block in the same response
                // untouched, unlike `rebuild_response_body`'s single-shot
                // replacement of the whole `content` array.
                let units = anthropic_response_text_units(body);
                let tool_calls = anthropic_response_tool_calls(body);
                if units.is_empty() && tool_calls.is_none() {
                    None
                } else {
                    Some((units_joined(&units), tool_calls, Some(units)))
                }
            }
        }
        RespFormat::Gemini => {
            let units = gemini_response_units(body);
            let tool_calls = gemini_response_tool_calls(body);
            if units.is_empty() && tool_calls.is_none() {
                None
            } else {
                Some((units_joined(&units), tool_calls, Some(units)))
            }
        }
        RespFormat::Bedrock => {
            let units = bedrock_response_units(body);
            let tool_calls = bedrock_response_tool_calls(body);
            if units.is_empty() && tool_calls.is_none() {
                None
            } else {
                Some((units_joined(&units), tool_calls, Some(units)))
            }
        }
        RespFormat::Responses => {
            let units = responses_response_units(body);
            let tool_calls = responses_response_tool_calls(body);
            if units.is_empty() && tool_calls.is_none() {
                None
            } else {
                Some((units_joined(&units), tool_calls, Some(units)))
            }
        }
        RespFormat::Cohere => {
            let units = cohere_response_units(body);
            let tool_calls = cohere_response_tool_calls(body);
            if units.is_empty() && tool_calls.is_none() {
                None
            } else {
                Some((units_joined(&units), tool_calls, Some(units)))
            }
        }
    }
}

#[entrypoint]
async fn configure(
    launcher: Launcher,
    Configuration(bytes): Configuration,
    metadata: Metadata,
) -> Result<()> {
    let config: Config = serde_json::from_slice(&bytes).map_err(|err| {
        anyhow!(
            "Failed to parse configuration '{}'. Cause: {}",
            String::from_utf8_lossy(&bytes),
            err
        )
    })?;

    // Fall back to the name of the API/LLM proxy this policy is attached to when
    // `consumerId` isn't explicitly configured, so TrustGuard can tell requests
    // from different proxies apart without per-instance config.
    //
    // IMPORTANT: `Metadata` must be injected as an #[entrypoint] parameter (as done
    // here), never constructed with `Metadata::new()` inside the function body --
    // that bypassed the PDK's supported extraction path and silently broke policy
    // enforcement on the real (managed) Omni Gateway during testing.
    let consumer_id = config
        .consumer_id
        .clone()
        .filter(|s| !s.trim().is_empty())
        .or(metadata.api_metadata.name);

    let ctx = Rc::new(PolicyContext { config, consumer_id });
    let ctx_for_request = Rc::clone(&ctx);

    let filter = on_request(move |rs, client| {
        let ctx = Rc::clone(&ctx_for_request);
        async move { request_filter(rs, ctx, client).await }
    })
    .on_response(move |rs, request_data, client| {
        let ctx = Rc::clone(&ctx);
        async move { response_filter(rs, request_data, ctx, client).await }
    });

    launcher.launch(filter).await?;
    Ok(())
}

